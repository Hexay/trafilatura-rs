"""Print crates/trafilatura-rs/src/trafilatura/metadata_xpaths.rs from trafilatura 1.11.0's metadata XPath objects
(run with .venv), or trafilatura2/metadata_xpaths.rs from 2.3.1's (run with .venv-t23)."""
from trafilatura import __version__, xpaths

LISTS = ["TITLE_XPATHS", "AUTHOR_XPATHS", "AUTHOR_DISCARD_XPATHS", "CATEGORIES_XPATHS", "TAGS_XPATHS"]


def raw(s):
    assert '"##' not in s
    return f'r##"{s}"##'


def main():
    out = [f"//! Generated by harness/gen_meta_xpaths.py from trafilatura {__version__} xpaths.py. Do not edit."]
    for name in LISTS:
        exprs = getattr(xpaths, name)
        out.append(f"pub const {name}: [&str; {len(exprs)}] = [")
        out.extend(f"    {raw(x.path)}," for x in exprs)
        out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
