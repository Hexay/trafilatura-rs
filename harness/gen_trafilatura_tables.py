"""Generate crates/trafilatura-rs/src/trafilatura/tables.rs from the reference interpreter: html.unescape's tables.
usage: gen_trafilatura_tables.py > crates/trafilatura-rs/src/trafilatura/tables.rs"""
import html
import sys
import unicodedata
from html.entities import html5


def rs(s):
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


def main():
    out = [f"//! Generated by harness/gen_trafilatura_tables.py from Python {sys.version.split()[0]} "
           f"(Unicode {unicodedata.unidata_version}). Do not edit."]
    ents = sorted(html5.items())
    out.append(f"pub static HTML5: [(&str, &str); {len(ents)}] = [")
    out += [f"    ({rs(k)}, {rs(v)})," for k, v in ents]
    out.append("];")
    inv = sorted(html._invalid_charrefs.items())
    out.append(f"pub static INVALID_CHARREFS: [(u32, &str); {len(inv)}] = [")
    out += [f"    (0x{k:x}, {rs(v)})," for k, v in inv]
    out.append("];")
    cps = sorted(html._invalid_codepoints)
    out.append(f"pub static INVALID_CODEPOINTS: [u32; {len(cps)}] = [")
    out += ["    " + ", ".join(f"0x{c:x}" for c in cps[i:i + 12]) + "," for i in range(0, len(cps), 12)]
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
