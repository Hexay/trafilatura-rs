"""Print crates/trafilatura-rs/src/trafilatura2/xpaths.rs from trafilatura 2.3.1's XPath objects
(run with .venv-t23)."""
from trafilatura import external, settings, xpaths

LISTS = ["BODY_XPATH", "COMMENTS_XPATH", "COMMENTS_DISCARD_XPATH", "REMOVE_COMMENTS_XPATH",
         "REMOVE_COMMENTS_AND_LISTS_XPATH", "RAW_TREE_PRUNE_XPATH", "OVERALL_DISCARD_XPATH", "TEASER_DISCARD_XPATH",
         "PRECISION_DISCARD_XPATH", "DISCARD_IMAGE_ELEMENTS"]


def raw(s):
    assert '"##' not in s
    return f'r##"{s}"##'


def main():
    out = ["//! Generated by harness/gen_xpaths2.py from trafilatura 2.3.1 (xpaths.py, settings.BASIC_CLEAN_XPATH,",
           "//! external.SANITIZED_XPATH). Do not edit."]
    for name in LISTS:
        exprs = getattr(xpaths, name)
        out.append(f"pub const {name}: [&str; {len(exprs)}] = [")
        out.extend(f"    {raw(x.path)}," for x in exprs)
        out.append("];")
    out.append(f"pub const BASIC_CLEAN_XPATH: &str = {raw(settings.BASIC_CLEAN_XPATH.path)};")
    out.append(f"pub const SANITIZED_XPATH: &str = {raw(external.SANITIZED_XPATH)};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
