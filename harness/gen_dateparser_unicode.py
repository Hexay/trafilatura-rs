"""Character table of the native dateparser port (crates/trafilatura-rs/src/dates/dateparser/unicode.rs).
usage: gen_dateparser_unicode.py > crates/trafilatura-rs/src/dates/dateparser/unicode.txt

A locale reads a date string after `_translate_numerals`, `normalize_unicode` (NFKD without Mn) and `str.lower()`.
Those are per character here, except where a character's result depends on its neighbours (a capital sigma's
lowercase, a digit run that is not all decimal, NFKD reordering of marks that are not dropped): such characters are
unknown, and a string holding one stays on Python. Lines (code points in hex):
  V <unidata_version> <regex_version>
  P <cp> [<cp>...]      what a locale reads for <cp>, where that is not <cp> itself (nothing: dropped)
  U <lo> <hi>           unknown
  H <lo> <hi>           Hangul syllables (decomposed arithmetically)
  F <cp> <cp>           `regex` IGNORECASE: <cp> folds to the second (one member of its class)
  W|D|S <lo> <hi>       `regex` \\w, \\d, \\s
  A|N|E|B <lo> <hi>     str.isalpha, isdigit, isdecimal, isspace"""
import sys
import unicodedata

import regex
from dateparser.utils import normalize_unicode
from regex import _regex

CODE_POINTS = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
HANGUL = (0xAC00, 0xD7A3)
FLAGS = int(regex.I | regex.U)
DIGIT = regex.compile(r"\d")


def processed(ch):
    """What a locale reads for `ch`, or None when that is not a per-character function."""
    if DIGIT.fullmatch(ch):
        if not ch.isdecimal():
            return None
        ch = str(unicodedata.decimal(ch))
    decomposed = unicodedata.normalize("NFKD", ch)
    if any(unicodedata.combining(c) and unicodedata.category(c) != "Mn" for c in decomposed):
        return None
    out = normalize_unicode(ch).lower()
    # a capital sigma's lowercase depends on its neighbours; _simplify lowers the string again
    if "Σ" in normalize_unicode(ch) or out.lower() != out:
        return None
    return out


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit_ranges(tag, cps):
    for lo, hi in ranges(cps):
        print(f"{tag} {lo:x} {hi:x}")


def check_hangul():
    for cp in range(HANGUL[0], HANGUL[1] + 1):
        s = cp - HANGUL[0]
        jamo = [0x1100 + s // 588, 0x1161 + s % 588 // 28] + ([0x11A7 + s % 28] if s % 28 else [])
        if processed(chr(cp)) != "".join(map(chr, jamo)) or any(processed(chr(j)) != chr(j) for j in jamo):
            raise SystemExit(f"Hangul U+{cp:04X} is not decomposed arithmetically")


def main():
    check_hangul()
    print("# Generated by harness/gen_dateparser_unicode.py. Do not edit.")
    print(f"V {unicodedata.unidata_version} {regex.__version__}")
    unknown = []
    for cp in CODE_POINTS:
        if HANGUL[0] <= cp <= HANGUL[1]:
            continue
        out = processed(chr(cp))
        if out is None:
            unknown.append(cp)
        elif out != chr(cp):
            print(f"P {cp:x}" + "".join(f" {ord(c):x}" for c in out))
    emit_ranges("U", unknown)
    print(f"H {HANGUL[0]:x} {HANGUL[1]:x}")
    for cp in CODE_POINTS:
        rep = min(_regex.get_all_cases(FLAGS, cp), default=cp)
        if min(rep, cp) != cp:
            print(f"F {cp:x} {rep:x}")
    for tag, pattern in (("W", r"\w"), ("D", r"\d"), ("S", r"\s")):
        emit_ranges(tag, [ord(m.group()) for m in regex.finditer(pattern, "".join(map(chr, CODE_POINTS)))])
    for tag, test in (("A", str.isalpha), ("N", str.isdigit), ("E", str.isdecimal), ("B", str.isspace)):
        emit_ranges(tag, [cp for cp in CODE_POINTS if test(chr(cp))])


if __name__ == "__main__":
    sys.exit(main())
