"""Per-character table for the native dateparser shortcut (see crates/trafilatura-rs/src/dates/dateparser/chars.rs).
usage: gen_dateparser_chars.py > crates/trafilatura-rs/src/dates/dateparser/chars.txt

A locale checks a date string after `_translate_numerals`, `normalize_unicode` (NFKD without Mn) and `str.lower()`.
Each character is classified by what that does to it, as seen by dateparser's `regex` patterns, whose word letters
are `[^\\W\\d_]`; letters are then folded to one member of their IGNORECASE class (`fold`), so a word that some
pattern matches case-insensitively folds to a word of the pattern. Lines (code points in hex):
  V <unidata_version> <regex_version>   the versions it holds for
  R <lo> <hi> <kind>                    I: a letter mapped to itself, M: a letter mapped to nothing, N: no letters
  P <cp> <cp>...                        a letter mapped to these letters
  H <lo> <hi>                           Hangul syllables (decomposed arithmetically into conjoining jamo)
  D <lo> <hi>                           `regex` \\d
  S <cp>...                             `regex` \\s
  A <cp> <cp>                           non-ASCII letter folded, where that is a letter of a timezone name
  G <cp>...                             IGNORECASE-equal to г (RE_SANITIZE_RUSSIAN)
  Q <cp>... / Z <cp>...                 APOSTROPHE_LOOK_ALIKE_CHARS / DASH_LOOK_ALIKE_CHARS
Anything else (mixed results, NFKD reordering, digits outside isdecimal) is unknown, which defers to Python."""
import sys
import unicodedata
from functools import cache

import regex
from dateparser import date as dp_date
from dateparser.timezone_parser import _tz_regexes
from dateparser.utils import normalize_unicode
from regex import _regex

FLAGS = int(regex.I | regex.U)
LETTER = regex.compile(r"[^\W\d_]")
DIGIT = regex.compile(r"\d")
SPACE = regex.compile(r"\s")
HANGUL = (0xAC00, 0xD7A3)
CODE_POINTS = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]


def is_letter(ch):
    return LETTER.fullmatch(ch) is not None


@cache
def fold_classes():
    parent = list(range(0x110000))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for cp in CODE_POINTS:
        for other in _regex.get_all_cases(FLAGS, cp):
            a, b = find(cp), find(other)
            if a != b:
                parent[max(a, b)] = min(a, b)
    members = {}
    for cp in CODE_POINTS:
        members.setdefault(find(cp), []).append(cp)
    rep = {}
    for group in members.values():
        lower = [cp for cp in group if chr(cp) == chr(cp).lower()] or group
        if len({is_letter(chr(cp)) for cp in group}) > 1:
            raise SystemExit(f"IGNORECASE class mixes letters and non-letters: {group}")
        for cp in group:
            rep[cp] = chr(min(lower))
    return rep


def fold(text):
    """`text` with every letter folded and every other character as '#'."""
    rep = fold_classes()
    return "".join(rep[ord(c)] if is_letter(c) else "#" for c in text)


def processed(ch):
    """What a locale sees of `ch`, folded; None when unknown."""
    if DIGIT.fullmatch(ch):
        return fold(str(unicodedata.decimal(ch))) if ch.isdecimal() else None
    decomposed = unicodedata.normalize("NFKD", ch)
    if any(unicodedata.combining(c) and unicodedata.category(c) != "Mn" for c in decomposed):
        return None
    return fold(normalize_unicode(ch).lower())


def classify(cp):
    ch = chr(cp)
    out = processed(ch)
    if out is None:
        return None
    if not is_letter(ch):
        return "N" if set(out) <= {"#"} else None
    if out == "":
        return "M"
    if "#" in out:
        return None
    return "I" if out == ch else out


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def check_hangul():
    for cp in range(HANGUL[0], HANGUL[1] + 1):
        s = cp - HANGUL[0]
        jamo = [0x1100 + s // 588, 0x1161 + s % 588 // 28] + ([0x11A7 + s % 28] if s % 28 else [])
        if classify(cp) != "".join(map(chr, jamo)) or any(classify(j) != "I" for j in jamo):
            raise SystemExit(f"Hangul U+{cp:04X} is not decomposed arithmetically")
    if fold("Σ".lower()) != fold("ς") or fold("ΑΣ".lower()[-1]) != fold("σ"):
        raise SystemExit("final sigma does not fold with σ")
    # a token holding a letter must never pass are_tokens_valid's isdigit()
    if any(is_letter(chr(cp)) and chr(cp).isdigit() for cp in CODE_POINTS):
        raise SystemExit("a letter is a digit")


def main():
    check_hangul()
    print("# Generated by harness/gen_dateparser_chars.py. Do not edit.")
    print(f"V {unicodedata.unidata_version} {regex.__version__}")
    kinds, mapped = {}, []
    for cp in CODE_POINTS:
        if HANGUL[0] <= cp <= HANGUL[1]:
            continue
        kind = classify(cp)
        if kind in ("I", "M", "N"):
            kinds.setdefault(kind, []).append(cp)
        elif kind is not None:
            mapped.append((cp, kind))
    rows = sorted((lo, hi, kind) for kind, cps in kinds.items() for lo, hi in ranges(cps))
    for lo, hi, kind in rows:
        print(f"R {lo:x} {hi:x} {kind}")
    for cp, out in mapped:
        print(f"P {cp:x} " + " ".join(f"{ord(c):x}" for c in out))
    print(f"H {HANGUL[0]:x} {HANGUL[1]:x}")
    for lo, hi in ranges(cp for cp in CODE_POINTS if DIGIT.fullmatch(chr(cp))):
        print(f"D {lo:x} {hi:x}")
    print("S " + " ".join(f"{cp:x}" for cp in CODE_POINTS if SPACE.fullmatch(chr(cp))))
    tz_letters = set(fold(_tz_regexes().names.pattern)) - {"#"}
    for cp in CODE_POINTS:
        if cp > 0x7F and is_letter(chr(cp)) and (rep := fold_classes()[cp]) in tz_letters:
            print(f"A {cp:x} {ord(rep):x}")
    print("G " + " ".join(f"{cp:x}" for cp in _regex.get_all_cases(FLAGS, ord("г"))))
    print("Q " + " ".join(f"{ord(c):x}" for c in dp_date.APOSTROPHE_LOOK_ALIKE_CHARS))
    print("Z " + " ".join(f"{ord(c):x}" for c in dp_date.DASH_LOOK_ALIKE_CHARS))


if __name__ == "__main__":
    sys.exit(main())
