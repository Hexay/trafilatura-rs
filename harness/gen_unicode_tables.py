"""Generate crates/trafilatura-rs/src/py/tables.rs from the reference interpreter (Python 3.12 = Unicode 15.0).
usage: gen_unicode_tables.py > crates/trafilatura-rs/src/py/tables.rs"""
import re
import sys
import unicodedata

WORD = re.compile(r"\w")


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def surrogate_safe(pred):
    return lambda c: not (0xD800 <= ord(c) <= 0xDFFF) and pred(c)


TABLES = {
    "WORD": surrogate_safe(lambda c: WORD.match(c) is not None),
    "ALNUM": surrogate_safe(str.isalnum),
    "DIGIT": surrogate_safe(str.isdigit),
    "PRINTABLE": surrogate_safe(str.isprintable),
}


def main():
    print(f"//! Generated by harness/gen_unicode_tables.py from Python {sys.version.split()[0]} "
          f"(Unicode {unicodedata.unidata_version}). Do not edit.")
    for name, pred in TABLES.items():
        rs = ranges(pred)
        print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
        for i in range(0, len(rs), 6):
            print("    " + " ".join(f"({a:#x}, {b:#x})," for a, b in rs[i:i + 6]))
        print("];")


if __name__ == "__main__":
    main()
