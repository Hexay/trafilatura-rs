"""Generate crates/trafilatura-rs/src/py/tables.rs from the reference interpreter (Python 3.12 = Unicode 15.0).
usage: gen_unicode_tables.py > crates/trafilatura-rs/src/py/tables.rs"""
import re
import sys
import unicodedata

WORD = re.compile(r"\w")


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def surrogate_safe(pred):
    return lambda c: not (0xD800 <= ord(c) <= 0xDFFF) and pred(c)


TABLES = {
    "WORD": surrogate_safe(lambda c: WORD.match(c) is not None),
    "ALNUM": surrogate_safe(str.isalnum),
    "DIGIT": surrogate_safe(str.isdigit),
    "PRINTABLE": surrogate_safe(str.isprintable),
}
# `gen_unicode_tables.py meta > crates/trafilatura-rs/src/py/tables_meta.rs` (Python 3.13: trafilatura 2.3.1's
# metadata and output helpers)
TABLES_META = {
    "ALPHA": surrogate_safe(str.isalpha),
    "PUNCT": surrogate_safe(lambda c: unicodedata.category(c)[0] == "P"),
}


def main():
    print(f"//! Generated by harness/gen_unicode_tables.py from Python {sys.version.split()[0]} "
          f"(Unicode {unicodedata.unidata_version}). Do not edit.")
    meta = sys.argv[1:] == ["meta"]
    for name, pred in (TABLES_META if meta else TABLES).items():
        rs = ranges(pred)
        print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
        for i in range(0, len(rs), 6):
            print("    " + " ".join(f"({a:#x}, {b:#x})," for a, b in rs[i:i + 6]))
        print("];")
    if meta:
        return
    zeros = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if unicodedata.decimal(chr(cp), -1) == 0:
            assert all(unicodedata.decimal(chr(cp + d), -1) == d for d in range(10)), hex(cp)
            zeros.append(cp)
    n_dec = sum(1 for cp in range(sys.maxunicode + 1)
                if not 0xD800 <= cp <= 0xDFFF and unicodedata.decimal(chr(cp), -1) >= 0)
    assert n_dec == 10 * len(zeros), (n_dec, len(zeros))
    print("/// Code points of Unicode decimal digit zero; each starts a run of ten (int() accepts them all).")
    print(f"pub static DECIMAL_ZEROS: [u32; {len(zeros)}] = [")
    for i in range(0, len(zeros), 12):
        print("    " + ", ".join(f"0x{c:x}" for c in zeros[i:i + 12]) + ",")
    print("];")


if __name__ == "__main__":
    main()
