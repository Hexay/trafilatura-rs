"""Generate crates/trafilatura-rs/src/py/case_tables.rs: what Python's str.title() does differently from per-char
uppercasing, and the titlecase letters (cased, but neither upper nor lower).
usage: gen_case_tables.py > crates/trafilatura-rs/src/py/case_tables.rs"""
import sys
import unicodedata


def rs(s):
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


def main():
    chars = [chr(c) for c in range(sys.maxunicode + 1) if not 0xD800 <= c <= 0xDFFF]
    title = [(c, c.title()) for c in chars if c.title() != c.upper()]
    lt = [c for c in chars if unicodedata.category(c) == "Lt"]
    print(f"//! Generated by harness/gen_case_tables.py from Python {sys.version.split()[0]} "
          f"(Unicode {unicodedata.unidata_version}). Do not edit.")
    print("/// Characters whose `str.title()` differs from `str.upper()`, with their titlecase.")
    print(f"pub static TITLE_SPECIAL: [(char, &str); {len(title)}] = [")
    print("\n".join(f"    ('\\u{{{ord(c):x}}}', {rs(t)})," for c, t in title))
    print("];")
    print("/// General category Lt.")
    print(f"pub static TITLECASE_LETTERS: [char; {len(lt)}] = [")
    print("\n".join(f"    '\\u{{{ord(c):x}}}'," for c in lt))
    print("];")


if __name__ == "__main__":
    main()
